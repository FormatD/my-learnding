import {test,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
test('evaluation downloads use saved records and preserve unfinished review',async({page,context},info)=>{
  test.skip(!process.env.EVALUATION_DOWNLOAD_USER);
  await page.goto('/');
  await page.getByLabel('家长用户名').fill(process.env.EVALUATION_DOWNLOAD_USER!);
  await page.getByLabel('家长密码').fill(process.env.EVALUATION_DOWNLOAD_PASSWORD!);
  await page.getByRole('button',{name:'登录',exact:true}).click();
  await page.route('**/api/v1/content',async route=>{const response=await route.fetch();await new Promise(resolve=>setTimeout(resolve,150));await route.fulfill({response});});
  await page.getByRole('button',{name:/内容与发布/}).click();
  const work=page.getByRole('region',{name:'映射建议与批量审核'});
  const id=process.env.EVALUATION_DOWNLOAD_RUN!;
  await work.getByLabel('查看建议运行').selectOption(id);
  await page.unroute('**/api/v1/content');
  const review=work.locator('article[aria-label]').first();
  const sentinel='尚未提交的受控校正，不应被当成保存决定';
  await review.getByLabel('本项审核依据').fill(sentinel);
  await review.getByLabel('本项决定').selectOption('Reject');
  await review.locator('input[type=checkbox]').first().check();
  const mapping=work.getByLabel('映射评测材料',{exact:true});
  await mapping.locator('summary').click();
  const wait=page.waitForEvent('download');
  await mapping.getByRole('button',{name:'下载评测材料'}).click();
  const file=await wait;expect(file.suggestedFilename()).toMatch(/^mapping-evaluation-/);
  const raw=fs.readFileSync((await file.path())!,'utf8'),captured=JSON.parse(raw);
  expect(raw).not.toContain(sentinel);
  const latest=await context.request.get('/api/v1/builder/mapping-runs/'+id);
  expect(latest.ok()).toBeTruthy();expect(raw).toBe(await latest.text());
  expect(captured.suggestions).toHaveLength(56);expect(captured.decisions).toHaveLength(2);
  await expect(review.getByLabel('本项审核依据')).toHaveValue(sentinel);
  await expect(review.getByLabel('本项决定')).toHaveValue('Reject');
  await expect(review.locator('input[type=checkbox]').first()).toBeChecked();
  fs.writeFileSync(path.join(process.env.EVALUATION_DOWNLOAD_DIRECTORY!,'mapping-download.json'),raw);
  await expect(mapping.getByRole('status')).toContainText('不代表质量达标');
  // A denied read creates no download and leaves the unfinished review intact.
  const detailPath='**/api/v1/builder/mapping-runs/'+id;
  let downloaded=0;page.on('download',()=>downloaded++);
  await page.route(detailPath,route=>route.fulfill({status:403,contentType:'application/json',body:JSON.stringify({title:'受控权限拒绝'})}));
  await mapping.getByRole('button',{name:'下载评测材料'}).click();
  await expect(mapping.getByRole('alert')).toHaveText('受控权限拒绝');expect(downloaded).toBe(0);
  await expect(review.getByLabel('本项审核依据')).toHaveValue(sentinel);
  await page.unroute(detailPath);
  // Leaving the page before a delayed read returns must not download stale material.
  let release!:()=>void,started!:()=>void;
  const gate=new Promise<void>(resolve=>release=resolve),seen=new Promise<void>(resolve=>started=resolve);
  await page.route(detailPath,async route=>{const response=await route.fetch();started();await gate;await route.fulfill({response});});
  await mapping.getByRole('button',{name:'下载评测材料'}).click();await seen;
  await expect(mapping.getByRole('button',{name:'正在准备下载…'})).toBeDisabled();
  await page.getByRole('button',{name:/辅助建库/}).click();release();await page.unroute(detailPath,{behavior:'wait'});
  const builder=page.getByLabel('候选评测材料',{exact:true});await builder.locator('summary').click();
  const next=page.waitForEvent('download');await builder.getByRole('button',{name:'下载评测材料'}).click();
  const builderFile=await next;const builderRaw=fs.readFileSync((await builderFile.path())!,'utf8');
  expect(builderFile.suggestedFilename()).toMatch(/^candidate-evaluation-/);
  const response=await context.request.get('/api/v1/builder');expect(response.ok()).toBeTruthy();expect(builderRaw).toBe(await response.text());
  expect(downloaded).toBe(1);
  fs.writeFileSync(path.join(process.env.EVALUATION_DOWNLOAD_DIRECTORY!,'builder-download.json'),builderRaw);
  await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({path:info.outputPath('evaluation-download-phone.png'),fullPage:true});
  await builder.screenshot({path:info.outputPath('evaluation-download-panel.png')});
});
