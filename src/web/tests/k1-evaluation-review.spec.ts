import { test, expect } from '@playwright/test';
import fs from 'node:fs';
test('local evaluation worksheet preserves pending labels and records only explicit review', async ({ page }, testInfo) => {
  test.skip(!process.env.EVALUATION_REVIEW_URL);
  await page.goto(process.env.EVALUATION_REVIEW_URL!);
  await expect(page.locator('#counts')).toHaveText('已记录 0 / 56；仍待标注 56');
  await page.locator('#approve').click();
  await expect(page.locator('#message')).toContainText('请明确');
  await page.locator('#eligibility').selectOption('measurable');
  const kc = await page.locator('#primary option').first().getAttribute('value');
  await page.locator('#primary').selectOption(kc!);
  await page.locator('#reviewer').fill('受控界面验收');
  await page.locator('#reason').fill('只验证保存流程，不作为正式金标准');
  await page.locator('#approve').click();
  await expect(page.locator('#counts')).toHaveText('已记录 1 / 56；仍待标注 55');
  await page.reload();
  await expect(page.locator('#counts')).toHaveText('已记录 1 / 56；仍待标注 55');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export').click();
  const download = await downloadPromise;
  const labels = JSON.parse(fs.readFileSync((await download.path())!, 'utf8'));
  expect(labels.labels).toHaveLength(160);
  expect(labels.labels.filter((r: any) => r.status === 'Pending')).toHaveLength(159);
  const approved = labels.labels.find((r: any) => r.status === 'Approved');
  expect(approved.reviewer).toBe('受控界面验收');
  expect(approved.inputHash).toMatch(/^[a-f0-9]{64}$/);
  await page.locator('#import').setInputFiles({ name: 'wrong.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...labels, datasetHash: 'wrong' })) });
  await expect(page.locator('#message')).toContainText('不对应');
  await expect(page.locator('#counts')).toContainText('已记录 1');
  await page.locator('#pending').click();
  await expect(page.locator('#counts')).toHaveText('已记录 0 / 56；仍待标注 56');
  await page.locator('#partition').selectOption('Development');
  await expect(page.locator('#counts')).toHaveText('已记录 0 / 104；仍待标注 104');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('evaluation-mobile.png'), fullPage: true });
  // Storage failure must remain visible after a successful in-memory record.
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw Error('Controlled storage failure'); }; });
  await page.locator('#eligibility').selectOption('activity');
  await page.locator('#reason').fill('受控不可测标签，仅测试保存失败提示');
  await page.locator('#approve').click();
  await expect(page.locator('#message')).toContainText('未能保存');
  await expect(page.locator('#counts')).toContainText('已记录 1 / 104');
});
